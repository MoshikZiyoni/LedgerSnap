def detect_us_bank(text: str) -> dict:
    """Detects a US bank from statement text, or defaults to Wells Fargo universal preset."""
    if not text:
        return US_BANKS_DIRECTORY["3000"]
    upper = text.upper()
    for bid, data in US_BANKS_DIRECTORY.items():
        for kw in data.get("keywords", []):
            if kw in upper:
                return data
    return US_BANKS_DIRECTORY["3000"]

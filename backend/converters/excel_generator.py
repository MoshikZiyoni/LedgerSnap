import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
import io
import csv
import re
from typing import List, Dict, Any, Optional

try:
    from backend.converters.qbo_generator import normalize_rtl_text
except ImportError:
    try:
        from converters.qbo_generator import normalize_rtl_text
    except ImportError:
        def normalize_rtl_text(t: str) -> str:
            return str(t)

def generate_excel(
    transactions: List[Dict[str, Any]],
    bank_name: str = "Bank Statement",
    summary: Optional[Dict[str, Any]] = None,
    currency: str = "USD"
) -> bytes:
    """
    Generates an Accountant Audit Workbook with Sheet 1 (Transactions) and
    Sheet 2 (Reconciliation Summary & Monthly Totals).
    """
    wb = openpyxl.Workbook()

    # Sheet 1: Transactions
    ws1 = wb.active
    ws1.title = "Transactions"
    ws1.views.sheetView[0].showGridLines = True

    # Palette
    HEADER_FILL = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid") # Slate 800
    HEADER_FONT = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    TITLE_FONT = Font(name="Calibri", size=14, bold=True, color="0F172A")
    ROW_FONT = Font(name="Calibri", size=11, color="1E293B")
    CREDIT_FONT = Font(name="Calibri", size=11, color="16A34A", bold=True)
    DEBIT_FONT = Font(name="Calibri", size=11, color="DC2626")
    THIN_BORDER = Border(
        left=Side(style='thin', color='E2E8F0'),
        right=Side(style='thin', color='E2E8F0'),
        top=Side(style='thin', color='E2E8F0'),
        bottom=Side(style='thin', color='E2E8F0')
    )

    curr_sym = "₪" if currency.upper() == "ILS" else ("€" if currency.upper() == "EUR" else ("£" if currency.upper() == "GBP" else "$"))
    num_fmt = f'"{curr_sym}"#,##0.00;("{curr_sym}"#,##0.00);"-"'

    # Title block
    ws1['A1'] = f"{bank_name} - Exported Transactions"
    ws1['A1'].font = TITLE_FONT
    ws1['A2'] = "Generated by LedgerSnap (ledger-snap.com) - Certified Accountant Workbook"
    ws1['A2'].font = Font(name="Calibri", size=9, italic=True, color="64748B")

    # Table Header Row (Row 4)
    headers = [
        "Date", 
        "Description", 
        "Type", 
        f"Debit ({curr_sym})", 
        f"Credit ({curr_sym})", 
        f"Net Amount ({curr_sym})", 
        f"Balance ({curr_sym})"
    ]
    for col_idx, header in enumerate(headers, 1):
        cell = ws1.cell(row=4, column=col_idx, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center" if col_idx in [1, 3] else ("right" if col_idx >= 4 else "left"), vertical="center")
        cell.border = THIN_BORDER

    ws1.row_dimensions[4].height = 24

    # Data Rows
    row_num = 5
    for t in transactions:
        amt = float(t.get("amount", 0.0))
        bal = t.get("balance")
        desc_clean = normalize_rtl_text(str(t.get("description", "")))
        t_type = t.get("type") or ("Credit" if amt >= 0 else "Debit")

        debit_val = abs(amt) if amt < 0 else None
        credit_val = amt if amt > 0 else None

        c_date = ws1.cell(row=row_num, column=1, value=str(t.get("date", "")))
        c_date.alignment = Alignment(horizontal="center")
        c_date.font = ROW_FONT
        c_date.border = THIN_BORDER

        c_desc = ws1.cell(row=row_num, column=2, value=desc_clean)
        c_desc.alignment = Alignment(horizontal="left")
        c_desc.font = ROW_FONT
        c_desc.border = THIN_BORDER

        c_type = ws1.cell(row=row_num, column=3, value=t_type)
        c_type.alignment = Alignment(horizontal="center")
        c_type.font = ROW_FONT
        c_type.border = THIN_BORDER

        c_deb = ws1.cell(row=row_num, column=4, value=debit_val)
        c_deb.number_format = num_fmt
        c_deb.font = DEBIT_FONT
        c_deb.alignment = Alignment(horizontal="right")
        c_deb.border = THIN_BORDER

        c_cred = ws1.cell(row=row_num, column=5, value=credit_val)
        c_cred.number_format = num_fmt
        c_cred.font = CREDIT_FONT
        c_cred.alignment = Alignment(horizontal="right")
        c_cred.border = THIN_BORDER

        c_amt = ws1.cell(row=row_num, column=6, value=amt)
        c_amt.number_format = num_fmt
        c_amt.font = CREDIT_FONT if amt >= 0 else DEBIT_FONT
        c_amt.alignment = Alignment(horizontal="right")
        c_amt.border = THIN_BORDER

        c_bal = ws1.cell(row=row_num, column=7, value=float(bal) if bal is not None else "")
        if bal is not None:
            c_bal.number_format = num_fmt
        c_bal.alignment = Alignment(horizontal="right")
        c_bal.font = ROW_FONT
        c_bal.border = THIN_BORDER

        # Alternating background
        if row_num % 2 == 0:
            for c in [c_date, c_desc, c_type, c_deb, c_cred, c_amt, c_bal]:
                c.fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")

        row_num += 1

    # Total Summary Row
    ws1.cell(row=row_num, column=2, value="TOTALS").font = Font(name="Calibri", size=11, bold=True)
    c_tot_deb = ws1.cell(row=row_num, column=4, value=f"=SUM(D5:D{row_num-1})")
    c_tot_deb.number_format = num_fmt
    c_tot_deb.font = Font(name="Calibri", size=11, bold=True, color="DC2626")
    c_tot_deb.border = Border(top=Side(style='thin', color='0F172A'), bottom=Side(style='double', color='0F172A'))

    c_tot_cred = ws1.cell(row=row_num, column=5, value=f"=SUM(E5:E{row_num-1})")
    c_tot_cred.number_format = num_fmt
    c_tot_cred.font = Font(name="Calibri", size=11, bold=True, color="16A34A")
    c_tot_cred.border = Border(top=Side(style='thin', color='0F172A'), bottom=Side(style='double', color='0F172A'))

    c_tot_net = ws1.cell(row=row_num, column=6, value=f"=SUM(F5:F{row_num-1})")
    c_tot_net.number_format = num_fmt
    c_tot_net.font = Font(name="Calibri", size=11, bold=True)
    c_tot_net.border = Border(top=Side(style='thin', color='0F172A'), bottom=Side(style='double', color='0F172A'))

    # Auto-adjust column widths for Sheet 1
    for col in ws1.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws1.column_dimensions[col_letter].width = max(max_len + 4, 13)
    ws1.column_dimensions['B'].width = 38

    # Sheet 2: Reconciliation & Monthly Summary
    ws2 = wb.create_sheet(title="Reconciliation & Audit")
    ws2.views.sheetView[0].showGridLines = True

    ws2['A1'] = "Statement Balance Reconciliation Audit"
    ws2['A1'].font = TITLE_FONT
    ws2['A2'] = f"Bank: {bank_name} | Currency: {currency} | Verification to the exact cent"
    ws2['A2'].font = Font(name="Calibri", size=10, italic=True, color="64748B")

    # Reconciliation Equation Block
    sec_header_fill = PatternFill(start_color="334155", end_color="334155", fill_type="solid")
    sec_header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")

    ws2['A4'] = "RECONCILIATION EQUATION"
    ws2['B4'] = "AMOUNT"
    ws2['A4'].fill = sec_header_fill
    ws2['A4'].font = sec_header_font
    ws2['B4'].fill = sec_header_fill
    ws2['B4'].font = sec_header_font
    ws2['B4'].alignment = Alignment(horizontal="right")

    tot_credits = sum(t["amount"] for t in transactions if t["amount"] > 0)
    tot_debits = sum(abs(t["amount"]) for t in transactions if t["amount"] < 0)
    net_diff = tot_credits - tot_debits
    op_bal = summary.get("opening_balance") if summary else None
    if op_bal is None and transactions and transactions[-1].get("balance") is not None:
        op_bal = round(float(transactions[-1]["balance"]) - float(transactions[-1]["amount"]), 2)
    op_val = float(op_bal) if op_bal is not None else 0.0
    calc_ending = op_val + net_diff
    target_ending = summary.get("ending_balance") if summary and summary.get("ending_balance") is not None else calc_ending

    reconciled_items = [
        ("Opening Balance (יתרת פתיחה)", op_val),
        ("(+) Total Deposits / Credits (סה\"כ זכות)", tot_credits),
        ("(-) Total Payments / Debits (סה\"כ חובה)", tot_debits),
        ("(=) Calculated Ending Balance (יתרה מחושבת)", calc_ending),
        ("Statement Target Ending Balance (יתרת סגירה בדף)", float(target_ending)),
        ("Reconciliation Discrepancy (הפרש)", round(abs(calc_ending - float(target_ending)), 2)),
    ]

    r = 5
    for label, val in reconciled_items:
        ws2.cell(row=r, column=1, value=label).font = ROW_FONT
        c = ws2.cell(row=r, column=2, value=val)
        c.number_format = num_fmt
        c.font = Font(name="Calibri", size=11, bold=(r in [5, 8, 9, 10]))
        c.alignment = Alignment(horizontal="right")
        r += 1

    # Monthly Breakdown Table
    r += 2
    ws2.cell(row=r, column=1, value="MONTHLY TRANSACTION BREAKDOWN").font = Font(name="Calibri", size=12, bold=True)
    r += 1

    m_headers = ["Month", "Tx Count", f"Credits ({curr_sym})", f"Debits ({curr_sym})", f"Net Change ({curr_sym})"]
    for idx, h in enumerate(m_headers, 1):
        cell = ws2.cell(row=r, column=idx, value=h)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center" if idx in [1, 2] else "right")
    r += 1

    months_list = summary.get("months", []) if summary else []
    if not months_list:
        months_list = [{
            "label": "Full Period",
            "count": len(transactions),
            "credits": tot_credits,
            "debits": tot_debits,
            "net": net_diff
        }]

    for m in months_list:
        ws2.cell(row=r, column=1, value=m.get("label", "")).font = ROW_FONT
        ws2.cell(row=r, column=2, value=m.get("count", 0)).alignment = Alignment(horizontal="center")
        
        c_cr = ws2.cell(row=r, column=3, value=float(m.get("credits", 0.0)))
        c_cr.number_format = num_fmt
        c_cr.font = CREDIT_FONT
        c_cr.alignment = Alignment(horizontal="right")

        c_deb = ws2.cell(row=r, column=4, value=float(m.get("debits", 0.0)))
        c_deb.number_format = num_fmt
        c_deb.font = DEBIT_FONT
        c_deb.alignment = Alignment(horizontal="right")

        c_net = ws2.cell(row=r, column=5, value=float(m.get("net", 0.0)))
        c_net.number_format = num_fmt
        c_net.font = Font(name="Calibri", size=11, bold=True)
        c_net.alignment = Alignment(horizontal="right")
        r += 1

    # Auto-adjust column widths for Sheet 2
    for col in ws2.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws2.column_dimensions[col_letter].width = max(max_len + 4, 16)
    ws2.column_dimensions['A'].width = 44

    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()

def generate_qbo_csv_3col(transactions: List[Dict[str, Any]], date_format: str = "MM/DD/YYYY") -> str:
    """
    QuickBooks Online 3-Column CSV format: Date, Description, Amount
    No extra metadata rows so QBO imports directly without mapping errors.
    """
    output = io.StringIO()
    writer = csv.writer(output, lineterminator='\n')
    writer.writerow(["Date", "Description", "Amount"])
    for t in transactions:
        d = str(t.get("date", ""))
        desc = normalize_rtl_text(str(t.get("description", ""))).replace('\n', ' ').strip()
        amt = float(t.get("amount", 0.0))
        writer.writerow([d, desc, f"{amt:.2f}"])
    return output.getvalue()

def generate_qbo_csv_4col(transactions: List[Dict[str, Any]], date_format: str = "MM/DD/YYYY") -> str:
    """
    QuickBooks Online 4-Column CSV format: Date, Description, Credit, Debit
    No extra metadata rows.
    """
    output = io.StringIO()
    writer = csv.writer(output, lineterminator='\n')
    writer.writerow(["Date", "Description", "Credit", "Debit"])
    for t in transactions:
        d = str(t.get("date", ""))
        desc = normalize_rtl_text(str(t.get("description", ""))).replace('\n', ' ').strip()
        amt = float(t.get("amount", 0.0))
        credit_str = f"{amt:.2f}" if amt > 0 else ""
        debit_str = f"{abs(amt):.2f}" if amt < 0 else ""
        writer.writerow([d, desc, credit_str, debit_str])
    return output.getvalue()

def generate_hashavshevet_excel(transactions: List[Dict[str, Any]], bank_name: str = "חשבון בנק") -> bytes:
    """
    Generates Hashavshevet (חשבשבת H-ERP) Excel format:
    Columns: תאריך ערך (DD/MM/YYYY), תאריך תנועה (DD/MM/YYYY), אסמכתא (Reference), פרטים (Description - RTL fixed), חובה (Debit), זכות (Credit), יתרה (Balance).
    Right-To-Left view enabled for Hebrew.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "חשבשבת"
    ws.views.sheetView[0].rightToLeft = True
    ws.views.sheetView[0].showGridLines = True

    HEADER_FILL = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
    HEADER_FONT = Font(name="Arial", size=11, bold=True, color="FFFFFF")
    ROW_FONT = Font(name="Arial", size=10, color="000000")
    THIN_BORDER = Border(
        left=Side(style='thin', color='CBD5E1'),
        right=Side(style='thin', color='CBD5E1'),
        top=Side(style='thin', color='CBD5E1'),
        bottom=Side(style='thin', color='CBD5E1')
    )

    headers = ["תאריך ערך", "תאריך תנועה", "אסמכתא", "פרטים", "חובה", "זכות", "יתרה"]
    for col_idx, h in enumerate(headers, 1):
        c = ws.cell(row=1, column=col_idx, value=h)
        c.fill = HEADER_FILL
        c.font = HEADER_FONT
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = THIN_BORDER
    ws.row_dimensions[1].height = 24

    for row_idx, t in enumerate(transactions, 2):
        d = str(t.get("date", ""))
        amt = float(t.get("amount", 0.0))
        bal = t.get("balance")
        desc = normalize_rtl_text(str(t.get("description", "")))
        ref = str(t.get("check_num") or t.get("check_number") or row_idx - 1)

        hova = abs(amt) if amt < 0 else None
        zchut = amt if amt > 0 else None

        row_vals = [d, d, ref, desc, hova, zchut, float(bal) if bal is not None else None]
        for col_idx, val in enumerate(row_vals, 1):
            cell = ws.cell(row=row_idx, column=col_idx, value=val)
            cell.font = ROW_FONT
            cell.border = THIN_BORDER
            if col_idx in [1, 2, 3]:
                cell.alignment = Alignment(horizontal="center")
            elif col_idx in [5, 6, 7]:
                cell.alignment = Alignment(horizontal="right")
                if val is not None:
                    cell.number_format = "#,##0.00"
            else:
                cell.alignment = Alignment(horizontal="right")

    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 14)
    ws.column_dimensions['D'].width = 38

    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()

def generate_hashavshevet_csv(transactions: List[Dict[str, Any]], encoding: str = "utf-8-sig") -> bytes:
    """
    Generates Hashavshevet CSV format with columns:
    תאריך ערך, תאריך תנועה, אסמכתא, פרטים, חובה, זכות, יתרה.
    encoded as UTF-8 with BOM (utf-8-sig) or Windows-1255.
    """
    output = io.StringIO()
    writer = csv.writer(output, lineterminator='\n')
    writer.writerow(["תאריך ערך", "תאריך תנועה", "אסמכתא", "פרטים", "חובה", "זכות", "יתרה"])

    for idx, t in enumerate(transactions, start=1):
        d = str(t.get("date", ""))
        amt = float(t.get("amount", 0.0))
        bal = t.get("balance")
        desc = normalize_rtl_text(str(t.get("description", ""))).replace('\n', ' ').strip()
        ref = str(t.get("check_num") or t.get("check_number") or idx)
        hova_str = f"{abs(amt):.2f}" if amt < 0 else ""
        zchut_str = f"{amt:.2f}" if amt > 0 else ""
        bal_str = f"{float(bal):.2f}" if bal is not None else ""
        writer.writerow([d, d, ref, desc, hova_str, zchut_str, bal_str])

    content_str = output.getvalue()
    if encoding.lower() in ["windows-1255", "cp1255", "1255"]:
        return content_str.encode("cp1255", errors="replace")
    return content_str.encode("utf-8-sig", errors="replace")

def generate_hashavshevet_dat(transactions: List[Dict[str, Any]]) -> bytes:
    """
    Generates standard Hashavshevet move record ASCII (.DAT) file format.
    Format per record: record_type(0), date, value_date, reference, debit, credit, details
    """
    lines = []
    for idx, t in enumerate(transactions, start=1):
        d = str(t.get("date", "")).replace('-', '/').replace('.', '/')
        amt = float(t.get("amount", 0.0))
        desc = normalize_rtl_text(str(t.get("description", "")))[:40].replace(',', ' ')
        ref = str(t.get("check_num") or t.get("check_number") or idx)[:9]
        hova = f"{abs(amt):.2f}" if amt < 0 else "0.00"
        zchut = f"{amt:.2f}" if amt > 0 else "0.00"
        line = f"0,{d},{d},{ref},{hova},{zchut},{desc}"
        lines.append(line)
    text = "\r\n".join(lines) + "\r\n"
    return text.encode("utf-8-sig", errors="replace")

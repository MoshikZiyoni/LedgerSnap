import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter
import io
from typing import List, Dict, Any

def generate_excel(transactions: List[Dict[str, Any]], bank_name: str = "Bank Statement") -> bytes:
    """
    Generates a beautifully styled, corporate-grade Excel (.xlsx) file.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Transactions"
    ws.views.sheetView[0].showGridLines = True

    # Palette
    HEADER_FILL = PatternFill(start_color="1E293B", end_color="1E293B", fill_type="solid") # Slate 800
    HEADER_FONT = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    TITLE_FONT = Font(name="Calibri", size=14, bold=True, color="0F172A")
    ROW_FONT = Font(name="Calibri", size=11, color="1E293B")
    CREDIT_FONT = Font(name="Calibri", size=11, color="16A34A", bold=True)
    DEBIT_FONT = Font(name="Calibri", size=11, color="DC2626")
    THIN_BORDER = Border(
        left=Side(style='thin', color='E2E8F0'),
        right=Side(style='thin', color='E2E8F0'),
        top=Side(style='thin', color='E2E8F0'),
        bottom=Side(style='thin', color='E2E8F0')
    )

    # Title block
    ws['A1'] = f"{bank_name} - Exported Transactions"
    ws['A1'].font = TITLE_FONT
    ws['A2'] = "Generated by BankToQBO (banktoqbo.com) - Certified Format"
    ws['A2'].font = Font(name="Calibri", size=9, italic=True, color="64748B")

    # Table Header Row (Row 4)
    headers = ["Date", "Description / Payee", "Type", "Amount ($)", "Balance ($)"]
    for col_idx, header in enumerate(headers, 1):
        cell = ws.cell(row=4, column=col_idx, value=header)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(horizontal="center" if col_idx in [1, 3] else ("right" if col_idx in [4, 5] else "left"), vertical="center")
        cell.border = THIN_BORDER

    ws.row_dimensions[4].height = 24

    # Data Rows
    row_num = 5
    for t in transactions:
        amt = float(t.get("amount", 0.0))
        bal = t.get("balance")

        c_date = ws.cell(row=row_num, column=1, value=t.get("date", ""))
        c_date.alignment = Alignment(horizontal="center")
        c_date.font = ROW_FONT
        c_date.border = THIN_BORDER

        c_desc = ws.cell(row=row_num, column=2, value=t.get("description", ""))
        c_desc.alignment = Alignment(horizontal="left")
        c_desc.font = ROW_FONT
        c_desc.border = THIN_BORDER

        c_type = ws.cell(row=row_num, column=3, value=t.get("type", "Credit" if amt >= 0 else "Debit"))
        c_type.alignment = Alignment(horizontal="center")
        c_type.font = ROW_FONT
        c_type.border = THIN_BORDER

        c_amt = ws.cell(row=row_num, column=4, value=amt)
        c_amt.number_format = "$#,##0.00"
        c_amt.font = CREDIT_FONT if amt >= 0 else DEBIT_FONT
        c_amt.alignment = Alignment(horizontal="right")
        c_amt.border = THIN_BORDER

        c_bal = ws.cell(row=row_num, column=5, value=float(bal) if bal is not None else "")
        if bal is not None:
            c_bal.number_format = "$#,##0.00"
        c_bal.alignment = Alignment(horizontal="right")
        c_bal.font = ROW_FONT
        c_bal.border = THIN_BORDER

        # Alternating background
        if row_num % 2 == 0:
            for c in [c_date, c_desc, c_type, c_amt, c_bal]:
                c.fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")

        row_num += 1

    # Total Summary Row
    ws.cell(row=row_num, column=2, value="TOTAL TRANSACTIONS").font = Font(name="Calibri", size=11, bold=True)
    total_cell = ws.cell(row=row_num, column=4, value=f"=SUM(D5:D{row_num-1})")
    total_cell.number_format = "$#,##0.00"
    total_cell.font = Font(name="Calibri", size=11, bold=True)
    total_cell.border = Border(top=Side(style='thin', color='0F172A'), bottom=Side(style='double', color='0F172A'))

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = max(len(str(cell.value or '')) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws.column_dimensions[col_letter].width = max(max_len + 4, 14)

    ws.column_dimensions['B'].width = 38 # Description column wider

    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()
